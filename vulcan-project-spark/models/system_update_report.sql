SELECT
   _id,
   scan_id,
   org_id,
   device_id,
   package_id,
   installation_status,
   coreq_package_id,
   package_name,
   package_description,
   package_version,
   current_installed_version,
   cast(package_release_date as timestamp) as package_release_date,
   package_vendor,
   package_type,
   package_severity,
   package_reboot_type,
   package_size,
   disk_space_required,
   package_tips,
   readme_url,
   license_url,
   device_display_name,
