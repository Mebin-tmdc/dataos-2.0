   cast(event_date_time as timestamp) as event_date_time,
   filtering_group_name,
   failure_reason,
   to_timestamp(from_unixtime(CAST(_nilus_load_id AS DOUBLE))) AS _nilus_load_id,
   _nilus_id
FROM (
    SELECT
        *,
        ROW_NUMBER() OVER (
            PARTITION BY _id
            ORDER BY CAST(_nilus_load_id AS BIGINT) DESC
        ) AS rn
    FROM s3depot.demolake04.system_update_report
)
WHERE rn = 1
